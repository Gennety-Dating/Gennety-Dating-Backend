/**
 * Тихие часы — одна реализация на весь продукт.
 *
 * Их было три: две в киевской зоне (`workers/quiet-hours.ts`,
 * `workers/re-engagement-schedule.ts`) и одна в зоне пользователя
 * (`services/profiler-schedule.ts`). Значения совпадали, но опорная система
 * координат — нет, и одна из реализаций была написана заново вместо того,
 * чтобы позвать соседнюю.
 *
 * Пока рынок один, разницы не видно. Второй рынок расщепил бы поведение молча:
 * человек в другой зоне получал бы уведомления по киевской ночи, и никакой
 * тест этого бы не заметил, потому что каждая из трёх копий по-своему права.
 *
 * Зона здесь — ПАРАМЕТР, а не константа, и это главное. Вызывающий обязан
 * назвать систему координат, в которой он рассуждает о ночи; «просто ночь»
 * бывает только на одном рынке.
 */

/** Начало окна тишины, местный час. */
export const QUIET_START_HOUR = 23;
/** Конец окна тишины, местный час (не включая). */
export const QUIET_END_HOUR = 9;

/**
 * Местный час (0..23) в указанной зоне, с учётом перехода на летнее время.
 *
 * `getUTCHours()` здесь однажды уже стоил продукту дорого: летом Киев это
 * UTC+3, и окно тишины уезжало на 02:00–12:00 — бот молчал в пик и рассылал
 * напоминания в шесть утра.
 */
export function localHourIn(date: Date, timeZone: string): number {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone,
    hour: "2-digit",
    hour12: false,
  }).formatToParts(date);
  const raw = parts.find((part) => part.type === "hour")?.value ?? "0";
  // Intl в некоторых средах отдаёт «24» для полуночи.
  return Number(raw) % 24;
}

/** Момент попадает в окно [23:00, 09:00) указанной зоны. Окно через полночь. */
export function isQuietHourIn(date: Date, timeZone: string): boolean {
  const hour = localHourIn(date, timeZone);
  return hour >= QUIET_START_HOUR || hour < QUIET_END_HOUR;
}
