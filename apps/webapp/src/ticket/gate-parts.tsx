// ── Cover panel («Оплатить и второй билет?») ──────────────────────────────

/**
 * The panel at the bottom edge (iOS `coverDock`, 2026-10-25): frosted glass
 * from edge to edge, top corners 30, light along the top rim, no grabber.
 *
 * «Беру на себя» asks before it spends: the first tap overlays the button with
 * a glass capsule «Подтвердить» + «✕», the second tap commits (`confirm-ask`).
 * With nothing in the wallet the tap goes straight to payment — the Stars sheet
 * is its own confirmation, exactly as the App Store sheet is on iOS.
 */
export function CoverDock({
  partnerSrc,
  partnerName,
  title,
  body,
  premiumNote,
  actionLabel,
  confirmLabel,
  cancelLabel,
  confirmHint,
  asks,
  working,
  failed,
  onSpend,
  footer,
  haptic,
}: {
  partnerSrc: string | null;
  partnerName: string | null;
  title: string;
  body: string;
  premiumNote: string | null;
  actionLabel: string;
  confirmLabel: string;
  cancelLabel: string;
  confirmHint: string;
  /** False when the tap goes straight to a payment sheet (empty wallet). */
  asks: boolean;
  working: boolean;
  /** Bumped by the parent when the server refused the spend. */
  failed: number;
  onSpend: () => void;
  footer: ReactNode;
  haptic: (kind: "press" | "select" | "refused") => void;
}): ReactElement {
  const [armedAt, setArmedAt] = useState<number | null>(null);
  const armed = armedAt != null;
  const workingRef = useRef(working);
  workingRef.current = working;

  // An abandoned question folds back by itself; a spend in flight holds it.
  useEffect(() => {
    if (armedAt == null) return;
    const id = window.setInterval(() => {
      if (shouldAutoClose(armedAt, Date.now(), workingRef.current)) setArmedAt(null);
    }, 250);
    return () => window.clearInterval(id);
  }, [armedAt]);

  // A refused spend is felt, not silent, and the capsule folds back.
  const lastFailed = useRef(failed);
  useEffect(() => {
    if (failed === lastFailed.current) return;
    lastFailed.current = failed;
    if (armedAt != null) {
      haptic("refused");
      setArmedAt(null);
    }
  }, [failed, armedAt, haptic]);

  const tapPrimary = (): void => {
    haptic("press");
    if (!asks) {
      onSpend();
      return;
    }
    setArmedAt(Date.now());
  };
  const tapConfirm = (): void => {
    if (!canConfirm(armedAt, Date.now())) return;
    haptic("press");
    onSpend();
  };
  const tapCancel = (): void => {
    haptic("press");
    setArmedAt(null);
  };

  return (
    <section className="gate-dock" aria-label={title}>
      <div className="gate-dock-head">
        <Avatar src={partnerSrc} name={partnerName} size={52} className="gate-portrait" />
        <div className="gate-dock-copy">
          <h2>{title}</h2>
          <p>{body}</p>
          {premiumNote ? <p className="gate-dock-premium">{premiumNote}</p> : null}
        </div>
      </div>
      <div className={`gate-ask${armed ? " is-armed" : ""}`} data-hold-ms={ASK_HOLD_MS}>
        <button
          type="button"
          className="gate-pill gate-ask-primary"
          disabled={working || armed}
          aria-hidden={armed}
          tabIndex={armed ? -1 : 0}
          onClick={tapPrimary}
        >
          {actionLabel}
        </button>
        {armed && (
          <div className="gate-ask-glass" role="group" aria-label={confirmHint}>
            <button
              type="button"
              className={`gate-pill gate-ask-confirm${working ? " is-working" : ""}`}
              disabled={working}
              onClick={tapConfirm}
            >
              {confirmLabel}
            </button>
            <button type="button" className="gate-ask-cancel" disabled={working} aria-label={cancelLabel} onClick={tapCancel}>
              <svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">
                <path d="M6.5 6.5 17.5 17.5M17.5 6.5 6.5 17.5" stroke="currentColor" strokeWidth="2.4" strokeLinecap="round" />
              </svg>
            </button>
          </div>
        )}
      </div>
      {footer}
    </section>
  );
}
