/**
 * Тактильные решения Mini App — чистая половина хаптики.
 *
 * Здесь живут ТОЛЬКО решения («что играть на этом событии»), а не диспетчер:
 * вызов `window.Telegram.WebApp.HapticFeedback` остаётся у вызывающего.
 * Так решения проверяемы тестами, а Telegram-глобал не нужен ни одному из них.
 *
 * Паритет с iOS (`Packages/DesignSystem/Sources/DesignSystem/Haptics.swift`)
 * намеренный, но **не дословный**, и разница честная: у Telegram нет
 * интенсивности — только стиль. Поэтому там, где iOS выражает величину силой
 * импульса, здесь она выражается весом стиля, и градаций ровно три, а не
 * континуум.
 */

/** Стили, которые понимает `HapticFeedback.impactOccurred`. */
export type ImpactStyle = "light" | "medium" | "heavy" | "rigid" | "soft";

/** Минимальный промежуток между щелчками шкалы. */
export const SCALE_MIN_GAP_MS = 40;

/**
 * Вес щелчка на шкале 1…`max`: глухо внизу, остро вверху.
 *
 * **Особой точки на максимуме нет намеренно.** Шкала химии в форме фидбека —
 * единственное место, где продукт узнаёт, сработало ли свидание, и хаптика,
 * награждающая десятку, смещала бы датасет пальцем. Градация сообщает
 * ВЕЛИЧИНУ, а не одобрение, поэтому она монотонна на всём диапазоне.
 * Ровно то же правило и та же реализация, что в iOS.
 */
export function rheostatStyle(level: number, max: number): ImpactStyle {
  const top = Math.max(1, max);
  const span = top - 1 || 1;
  const position = (Math.min(top, Math.max(1, level)) - 1) / span;
  if (position < 0.34) return "soft";
  if (position < 0.67) return "light";
  return "rigid";
}

/**
 * Прошло ли достаточно времени, чтобы сыграть следующий щелчок шкалы.
 *
 * Drag по шкале даёт поток шагов, и без промежутка это дребезг, а не отсчёт —
 * та же причина, по которой натяжение в жесте поиска на iOS режется сеткой, а
 * колесо онбординга здесь уже имеет `HAPTIC_MIN_GAP_MS`.
 *
 * Подавленный щелчок вызывающий НЕ должен записывать как сыгранный: значение
 * всё равно изменилось, и следующий кадр обязан сыграть то, что под пальцем к
 * тому моменту.
 */
export function shouldTickScale(lastTickAt: number, now: number): boolean {
  return now - lastTickAt >= SCALE_MIN_GAP_MS;
}

/** Что произошло с границей рынка между двумя проверками. */
export type BoundaryEvent = "none" | "exit" | "enter";

/**
 * Пересечение границы рынка, а не её состояние.
 *
 * Гейт точки отправления пересчитывается на КАЖДОМ пане карты, поэтому играть
 * от состояния значило бы вибрировать всё время, пока пин снаружи, — то есть
 * ровно тот вибро-шум, который продукт запрещает. Играет только переход.
 *
 * `was === null` — карта только что открылась: сторона границы ещё неизвестна,
 * и первый расчёт обязан молчать. Иначе человек, вернувшийся к черновику с
 * точкой вне рынка, получал бы упор в границу при появлении экрана, ничего не
 * пересекая.
 */
export function boundaryEvent(was: boolean | null, isInside: boolean): BoundaryEvent {
  if (was === null || was === isInside) return "none";
  return isInside ? "enter" : "exit";
}
