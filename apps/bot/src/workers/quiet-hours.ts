/**
 * Тихие часы бота — 23:00–09:00 Europe/Kyiv.
 *
 * Проактивные сообщения (re-engagement, напоминания, объявления) не уходят в
 * это окно. Крон продолжает тикать; каждый воркер зовёт `isQuietHours` перед
 * отправкой.
 *
 * **Правило живёт в `@gennety/shared`, здесь остался только выбор зоны.** Копий
 * было три — две киевские и одна в зоне пользователя, — и та, что в зоне
 * пользователя, была написана заново вместо вызова соседней. Пока рынок один,
 * разницы не видно; второй расщепил бы поведение молча, и каждая копия была бы
 * по-своему права.
 *
 * Киевская зона здесь — не «просто ночь», а СОЗНАТЕЛЬНЫЙ выбор: эти воркеры
 * рассылают по всей базе разом, и до второго рынка «ночь» у них ровно одна.
 * Когда рынков станет два, менять придётся эту строку, а не искать три
 * реализации.
 */
import {
  DEFAULT_TIME_ZONE,
  isQuietHourIn,
  QUIET_END_HOUR,
  QUIET_START_HOUR,
} from "@gennety/shared";

export const QUIET_START = QUIET_START_HOUR;
export const QUIET_END = QUIET_END_HOUR;
export const QUIET_TZ = DEFAULT_TIME_ZONE;

/** Момент попадает в киевское окно тишины [23:00, 09:00). */
export function isQuietHours(now: Date = new Date()): boolean {
  return isQuietHourIn(now, QUIET_TZ);
}
