/**
 * Did the date actually happen — the pure half.
 *
 * ── Почему эта фича вообще существует ────────────────────────────────────
 *
 * `Match.status = 'completed'` не отвечает на вопрос «свидание состоялось?».
 * Его ставит промпт обратной связи через 24 часа после `agreedTime` —
 * независимо от того, пришёл кто-нибудь или нет. Форма спрашивает химию 1–10
 * и второе свидание, то есть вопросы ПРО свидание; про сам факт встречи не
 * спрашивает никто. Поэтому no-show в продукте не измерялся ничем, а метрика
 * «доля no-show от проданных билетов» существовала только на бумаге.
 *
 * ── Решение, которое держит всю конструкцию ──────────────────────────────
 *
 * **Вопрос задаётся всегда; улики меняют формулировку, а не факт вопроса.**
 *
 * Соблазн был обратный: собрать улики (прокси-чат, что человек писал агенту),
 * прогнать через дешёвую модель и, если «похоже, встретились», не спрашивать.
 * Это ошибка, и её цена несимметрична. Спросить у того, кто уже всё рассказал,
 * — выглядит как агент без памяти: неприятно, но поправимо. Решить за того,
 * кто ничего не говорил, — записать выдуманный факт в метрику, ради которой
 * всё и делается, и написать «как прошло свидание?» человеку, которого
 * продинамили.
 *
 * Претензия «у агента нет памяти» на самом деле не про то, что спросили. Она
 * про то, что спросили КАК БУДТО НИЧЕГО НЕ ЗНАЕМ. «Вчера ты написал, что она
 * не пришла — всё так?» и спрашивает, и помнит одновременно.
 *
 * Отсюда правило, которое нельзя ослаблять: **классификатор улик никогда не
 * пишет `dateAttended*`.** Он выбирает одну из трёх формулировок. Ошибся —
 * получили странное предложение, а не фальшивую метрику. Пишет только ответ
 * живого человека.
 *
 * ── Явка — свойство ПАРЫ ─────────────────────────────────────────────────
 *
 * Свидание либо состоялось, либо нет; оно не может состояться для одного и не
 * состояться для другого. Поэтому одного достоверного «да» достаточно, чтобы
 * закрыть вопрос для матча. Две колонки существуют не для того, чтобы считать
 * явку по-разному для каждой стороны, а потому что стороны могут ответить
 * по-разному — и это реальное состояние (`disputed`), которое должно быть
 * видно в админке, а не схлопнуто молча в одно значение. Такое расхождение
 * редкое, но осмысленное: получасовая неловкая прогулка для одного «мы
 * встретились», для другого «свидания не было».
 */

import type { Language } from "@gennety/shared";

// ---------------------------------------------------------------------------
// Исходы ветки «не встретились»
// ---------------------------------------------------------------------------

/**
 * Почему свидание не состоялось.
 *
 * Обычная строка, а не Prisma-enum — как `ticketStatus`, `coordMethod` и
 * `venueChangeStatus`: новое значение не стоит миграции на живом проде.
 *
 * Различение здесь не косметическое. «Свидание не состоялось» и «партнёр не
 * пришёл» — разные факты и для метрики, и для возврата билета: первое бывает
 * ничьей виной, второе имеет пострадавшего.
 */
export const ATTENDANCE_OUTCOMES = [
  /** Партнёр не пришёл. Единственный исход, который и есть no-show. */
  "no_show_partner",
  /** Не смог прийти сам отвечающий. */
  "no_show_self",
  /** Перенесли/не сложилось по обоюдному согласию — пострадавшего нет. */
  "both_rescheduled",
  /** Что-то ещё; текст остаётся в таймлайне чата. */
  "other",
] as const;

export type AttendanceOutcome = (typeof ATTENDANCE_OUTCOMES)[number];

export function isAttendanceOutcome(value: unknown): value is AttendanceOutcome {
  return (
    typeof value === "string" && (ATTENDANCE_OUTCOMES as readonly string[]).includes(value)
  );
}

// ---------------------------------------------------------------------------
// Вердикт по паре
// ---------------------------------------------------------------------------

/**
 * `unknown` — никто не ответил. Это НЕ «не встретились»: рендерить его как
 * `false` значит выдумать no-show из молчания, а молчание после свидания —
 * самый обычный исход.
 */
export type PairAttendance = "met" | "not_met" | "disputed" | "unknown";

export interface AttendanceSides {
  dateAttendedA: boolean | null;
  dateAttendedB: boolean | null;
}

/**
 * Явка пары из двух ответов.
 *
 * Одно «да» закрывает вопрос: свидание — общее событие, и человек, который на
 * нём был, знает это про обоих. Одно «нет» при молчащем партнёре тоже
 * принимается — иначе no-show нельзя было бы зафиксировать никогда, ведь тот,
 * кто не пришёл, отвечать не станет.
 */
export function resolvePairAttendance(sides: AttendanceSides): PairAttendance {
  const { dateAttendedA: a, dateAttendedB: b } = sides;
  if (a === null && b === null) return "unknown";
  if (a === true && b === false) return "disputed";
  if (a === false && b === true) return "disputed";
  if (a === true || b === true) return "met";
  return "not_met";
}

/**
 * Был ли это no-show — то есть остался ли кто-то ждать напрасно.
 *
 * Строго уже, чем «свидание не состоялось»: обоюдный перенос — не no-show,
 * там никто не пострадал. Возвращает `null`, когда ответов нет вовсе, чтобы
 * вызывающий мог показать «нет данных» вместо нуля.
 */
export function isNoShow(
  sides: AttendanceSides & {
    attendanceOutcomeA: string | null;
    attendanceOutcomeB: string | null;
  },
): boolean | null {
  const verdict = resolvePairAttendance(sides);
  if (verdict === "unknown") return null;
  if (verdict === "met") return false;
  // `disputed` тоже сюда: если одна сторона говорит «он не пришёл», это
  // заявление о no-show, даже если другая считает иначе. Разбирает человек.
  return [sides.attendanceOutcomeA, sides.attendanceOutcomeB].some(
    (o) => o === "no_show_partner" || o === "no_show_self",
  );
}

// ---------------------------------------------------------------------------
// Тон вопроса
// ---------------------------------------------------------------------------

/**
 * Какой из трёх формулировок задать вопрос.
 *
 * `unknown` — дефолт и подавляющее большинство случаев. Две другие ветки
 * требуют сильной улики; см. `attendance-evidence.ts`, где решается, что
 * считать сильным.
 */
export type AttendanceTone = "unknown" | "likely_met" | "likely_not_met";

// ---------------------------------------------------------------------------
// Разбор ответа
// ---------------------------------------------------------------------------

export type AttendanceReply = "yes" | "no" | "unclear";

const YES_PHRASES = new Set([
  // ru
  "да", "ага", "угу", "конечно", "да встретились", "встретились", "виделись",
  "да виделись", "были", "да были", "всё прошло", "все прошло", "да всё хорошо",
  "да все хорошо", "да всё отлично", "да все отлично", "да конечно",
  // uk
  "так", "звісно", "звiсно", "так зустрілися", "зустрілися", "зустрiлися",
  "бачилися", "так бачилися",
  // en
  "yes", "yeah", "yep", "we met", "yes we met", "we did", "sure",
  // de / pl
  "ja", "tak", "spotkaliśmy się", "spotkalismy sie",
]);

const NO_PHRASES = new Set([
  // ru
  "нет", "не встретились", "не виделись", "не пришла", "не пришел", "не пришёл",
  "нет не встретились", "не состоялось", "не получилось", "не сложилось",
  "никто не пришел", "никто не пришёл", "не дождался", "не дождалась",
  // uk
  "ні", "нi", "не зустрілися", "не зустрiлися", "не бачилися", "не прийшла",
  "не прийшов", "не вийшло",
  // en
  "no", "nope", "we didn't", "we didnt", "didn't happen", "didnt happen",
  "she didn't come", "he didn't come", "no show",
  // de / pl
  "nein", "nie", "nie spotkaliśmy się", "nie spotkalismy sie",
]);

/** За этой длиной короткий ответ кончается и начинается рассказ. */
const MAX_SHORT_REPLY_LEN = 40;

/**
 * Детерминированный разбор короткого ответа, без LLM.
 *
 * Почему не модель: этот предикат стоит на горячем пути маршрутизации текста,
 * а ошибки несимметричны — пропущенное «да» деградирует до `unclear` и уходит
 * агенту, который переспросит, тогда как ложное срабатывание записывает
 * неверный факт в метрику. То же рассуждение, по которому детерминированным
 * сделан `isProfilerRefusal`.
 *
 * Совпадение — по ВСЕМУ сообщению, не по подстроке: «нет, ну мы встретились,
 * просто быстро разошлись» начинается с «нет» и означает «да».
 */
export function classifyAttendanceReply(text: string): AttendanceReply {
  const normalized = text
    .trim()
    .toLocaleLowerCase()
    .replace(/[.!?…,]+$/gu, "")
    .replace(/\s+/gu, " ")
    .trim();

  if (!normalized || normalized.length > MAX_SHORT_REPLY_LEN) return "unclear";
  if (YES_PHRASES.has(normalized)) return "yes";
  if (NO_PHRASES.has(normalized)) return "no";
  return "unclear";
}

/**
 * Ключ i18n для вопроса под выбранный тон.
 *
 * Отдельной функцией, а не `switch` по месту, чтобы добавление тона ломало
 * типизацию здесь, а не молча теряло ветку в хендлере.
 */
export function attendanceQuestionKey(
  tone: AttendanceTone,
): "attendanceAsk" | "attendanceAskLikelyMet" | "attendanceAskLikelyNotMet" {
  switch (tone) {
    case "likely_met":
      return "attendanceAskLikelyMet";
    case "likely_not_met":
      return "attendanceAskLikelyNotMet";
    case "unknown":
      return "attendanceAsk";
  }
}

/** Узкий тип для мест, где нужен только язык участника. */
export type AttendanceLanguage = Language;
