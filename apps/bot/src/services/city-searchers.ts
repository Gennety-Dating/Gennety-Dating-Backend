import { prisma } from "@gennety/db";
import { env } from "../config.js";

/**
 * «Сколько людей в поиске в твоём городе» — счётчик под коллажем на «Сегодня».
 *
 * **Число никогда не выдумывается.** Решается только одно: с какого момента его
 * вообще стоит произносить. На старте рынка честный ответ — единицы, и подпись
 * «4 в поиске в Киеве» работает против сцены сильнее, чем её отсутствие.
 * Поэтому ниже порога счётчика нет вовсе: коллаж крутится, строки с числом
 * просто не существует, и она появляется сама, когда город дорастёт.
 *
 * **Порог применяет сервер, а не клиент** (решение основателя 2026-09-08), и
 * это не деталь реализации:
 *
 *  - у клиента не остаётся своей политики, которой он мог бы разойтись с
 *    сервером и с Telegram-поверхностью;
 *  - порог живёт в переменной окружения, то есть меняется выкатом бэкенда, а
 *    не новым релизом в App Store — иначе подбор числа стоил бы ревью Apple;
 *  - `null` в ответе не значит «не смогли посчитать»: он значит «показывать
 *    нечего», и клиенту нечего додумывать.
 *
 * **Гистерезиса сознательно нет.** Город, застрявший ровно на границе, будет
 * то показывать счётчик, то прятать. Лечится это либо состоянием на сервере
 * (лишняя колонка ради косметики), либо флагом от клиента — а флаг от клиента
 * вернул бы клиенту право держать счётчик показанным всегда, то есть ровно ту
 * политику, которую этот модуль и уносит на сервер. Если мигание проявится на
 * живом городе, чинить его надо серверным состоянием, а не параметром запроса.
 */

/** Ниже этого числа счётчик не показывается. Основатель выбрал 250. */
export const SEARCHERS_VISIBILITY_THRESHOLD = Math.max(
  0,
  Number(env.SEARCHERS_COUNTER_MIN ?? 250),
);

/**
 * Сколько людей сейчас в поиске в городе пользователя, либо `null`.
 *
 * Считаются все, кто в пуле подбора этого города, — без фильтра по полу и
 * предпочтениям. Это социальный факт про город («здесь есть люди»), а не
 * персональная выборка кандидатов: тем занимается `agent-insights.cityPool`,
 * и смешивать их нельзя, иначе одно и то же слово «в поиске» значило бы на
 * двух экранах разное.
 *
 * Сам пользователь из счёта НЕ исключается: он тоже в поиске, и вычитать его
 * значило бы показывать число, которое не сходится ни с чем.
 *
 * `status: "active"` уже несёт всю нужную семантику — `paused` (осознанная
 * пауза), `frozen` (мягкое удаление), модерационные состояния и незавершённый
 * онбординг в это значение не попадают.
 */
export async function countCitySearchers(userId: string): Promise<number | null> {
  const user = await prisma.user.findUnique({
    where: { id: userId },
    select: { profile: { select: { homeCityKey: true } } },
  });

  const homeCityKey = user?.profile?.homeCityKey;
  if (!homeCityKey) return null;

  const count = await prisma.user.count({
    where: {
      status: "active",
      onboardingStep: "completed",
      profile: { homeCityKey },
    },
  });

  return count >= SEARCHERS_VISIBILITY_THRESHOLD ? count : null;
}
